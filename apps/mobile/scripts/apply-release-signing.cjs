#!/usr/bin/env node
// Run after `npx expo prebuild --platform android`, before building.
// `android/app/build.gradle` is regenerated from scratch by prebuild every
// time, wiping out the release signingConfig — this reinserts it so
// `./gradlew bundleRelease` produces an AAB signed with the same
// pamarket.keystore key already used for com.pamarket.app on Play Console.
const fs = require("fs");
const path = require("path");

const buildGradlePath = path.join(__dirname, "..", "android", "app", "build.gradle");

if (!fs.existsSync(buildGradlePath)) {
  console.error(`[apply-release-signing] not found: ${buildGradlePath} — run expo prebuild first.`);
  process.exit(1);
}

let gradle = fs.readFileSync(buildGradlePath, "utf8");

if (gradle.includes("hasReleaseSigning")) {
  console.log("[apply-release-signing] already applied, skipping.");
  process.exit(0);
}

const beforeAndroidBlock = `apply from: new File(["node", "--print", "require('path').dirname(require.resolve('@sentry/react-native/package.json'))"].execute().text.trim(), "sentry.gradle")

android {`;

const afterAndroidBlock = `apply from: new File(["node", "--print", "require('path').dirname(require.resolve('@sentry/react-native/package.json'))"].execute().text.trim(), "sentry.gradle")

// Release signing for local (non-EAS) builds — reads android/keystore.properties
// (gitignored, since this whole android/ folder is regenerated by \`expo prebuild\`
// anyway). Same com.pamarket.app signing key used by the legacy Capacitor app's
// build, so uploads to the existing Play Console listing verify correctly.
def keystorePropertiesFile = rootProject.file("keystore.properties")
def keystoreProperties = new Properties()
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(new FileInputStream(keystorePropertiesFile))
}
def hasReleaseSigning = keystorePropertiesFile.exists() && keystoreProperties['storeFile']

android {`;

if (!gradle.includes(beforeAndroidBlock)) {
  console.error("[apply-release-signing] sentry.gradle apply block not found — build.gradle shape may have changed.");
  process.exit(1);
}
gradle = gradle.replace(beforeAndroidBlock, afterAndroidBlock);

const beforeSigning = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }
    buildTypes {
        debug {
            signingConfig = signingConfigs.debug
        }
        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig = signingConfigs.debug`;

const afterSigning = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        release {
            if (hasReleaseSigning) {
                storeFile file(keystoreProperties['storeFile'])
                storePassword keystoreProperties['storePassword']
                keyAlias keystoreProperties['keyAlias']
                keyPassword keystoreProperties['keyPassword']
            }
        }
    }
    buildTypes {
        debug {
            signingConfig = signingConfigs.debug
        }
        release {
            signingConfig = hasReleaseSigning ? signingConfigs.release : signingConfigs.debug`;

if (!gradle.includes(beforeSigning)) {
  console.error("[apply-release-signing] signingConfigs block not found — build.gradle shape may have changed.");
  process.exit(1);
}
gradle = gradle.replace(beforeSigning, afterSigning);

const beforePackaging = `    packagingOptions {
        jniLibs {
            def enableLegacyPackaging = findProperty('expo.useLegacyPackaging') ?: 'false'
            useLegacyPackaging = enableLegacyPackaging.toBoolean()
        }
    }`;

const afterPackaging = `    packagingOptions {
        jniLibs {
            def enableLegacyPackaging = findProperty('expo.useLegacyPackaging') ?: 'false'
            useLegacyPackaging = enableLegacyPackaging.toBoolean()
        }
    }
    // Windows MAX_PATH (260 chars) workaround: the autolinked codegen
    // targets' CMake object-file paths embed this project's full absolute
    // source path, and RelWithDebInfo (release)'s longer folder name pushes
    // some paths just over the limit even though Debug's shorter name fits.
    // Relocating the .cxx working directory outside the deeply-nested repo
    // path keeps every generated path short regardless of build type.
    externalNativeBuild {
        cmake {
            buildStagingDirectory "C:/rncxx"
        }
    }`;

if (gradle.includes(beforePackaging)) {
  gradle = gradle.replace(beforePackaging, afterPackaging);
}

fs.writeFileSync(buildGradlePath, gradle);
console.log("[apply-release-signing] patched release signingConfig + CMake staging directory.");
