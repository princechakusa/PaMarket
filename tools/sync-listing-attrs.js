// Writes js/listing-attrs.js from the mobile app's attribute schema so the
// website shows the same labels ("Type", "Quantity", "Age Group") instead of
// raw keys like "atype". Run after editing apps/mobile/lib/*.json:
//   node tools/sync-listing-attrs.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const attrs = JSON.parse(fs.readFileSync(path.join(ROOT, 'apps/mobile/lib/category-attrs.json'), 'utf8'));
const subcats = JSON.parse(fs.readFileSync(path.join(ROOT, 'apps/mobile/lib/subcategories.json'), 'utf8'));

const schema = {};
for (const [cat, fields] of Object.entries(attrs)) {
  schema[cat] = fields.map((f) => {
    const out = { k: f.key, l: f.label };
    if (f.type === 'chips') out.chips = 1;
    if (f.suffix) out.s = f.suffix;
    return out;
  });
}
const subLabels = {};
for (const [cat, list] of Object.entries(subcats)) {
  subLabels[cat] = Object.fromEntries(list.map((s) => [s.key, s.label]));
}

const body = `// GENERATED by tools/sync-listing-attrs.js from apps/mobile/lib/*.json. Do not edit by hand.
(function (root, factory) {
  var api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.PMListingAttrs = api;
})(typeof window !== 'undefined' ? window : this, function () {
  var SCHEMA = ${JSON.stringify(schema)};
  var SUBCATS = ${JSON.stringify(subLabels)};
  function cap(v) {
    var s = String(v).trim();
    return s ? s.charAt(0).toUpperCase() + s.slice(1) : s;
  }
  function fmt(v, suffix) {
    var s = Array.isArray(v) ? v.map(cap).join(', ') : cap(v);
    if (suffix && /^\\d[\\d,.]*$/.test(String(v).trim())) s = Number(String(v).replace(/,/g, '')).toLocaleString('en-US') + ' ' + suffix;
    return s;
  }
  function empty(v) { return v == null || v === '' || (Array.isArray(v) && !v.length); }
  // Returns { specs: [{label, value}], features: {label, items} | null,
  // subcategory: label | null } for a listing's category + attributes.
  function describe(category, attributes, listingCondition) {
    var a = attributes && typeof attributes === 'object' ? attributes : {};
    var fields = SCHEMA[category] || SCHEMA.other || [];
    var specs = [], features = null;
    for (var i = 0; i < fields.length; i++) {
      var f = fields[i], v = a[f.k];
      if (f.k === 'condition' && empty(v)) v = listingCondition;
      if (empty(v)) continue;
      if (f.chips) { features = { label: f.l, items: (Array.isArray(v) ? v : [v]).map(cap) }; continue; }
      specs.push({ label: f.l, value: fmt(v, f.s) });
    }
    var sub = a.subcat && SUBCATS[category] ? (SUBCATS[category][a.subcat] || null) : null;
    return { specs: specs, features: features, subcategory: sub };
  }
  return { describe: describe };
});
`;
fs.writeFileSync(path.join(ROOT, 'js', 'listing-attrs.js'), body, 'utf8');
console.log('js/listing-attrs.js written (' + Object.keys(schema).length + ' categories)');
